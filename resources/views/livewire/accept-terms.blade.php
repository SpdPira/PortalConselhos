                <pre class="font-sans">

<strong>TERMO DE CONSENTIMENTO, RESPONSABILIDADE, USO E GOVERNANÇA DA INFORMAÇÃO</strong>


O presente Termo de Consentimento, Responsabilidade, Uso e Governança da Informação estabelece as regras, diretrizes, obrigações, responsabilidades e condições de utilização da plataforma eletrônica denominada Portal dos 
Conselhos Municipais de Pirassununga, mantida pela Prefeitura Municipal de Pirassununga.

A plataforma possui caráter público, institucional e permanente, sendo destinada à centralização, organização, gerenciamento, armazenamento e divulgação de informações relacionadas aos Conselhos Municipais de Políticas 
Públicas, seus membros, atos administrativos, deliberações, documentos oficiais e demais registros de interesse coletivo.

O Portal constitui instrumento oficial de transparência pública, participação social, controle cidadão e publicidade administrativa, observando os princípios constitucionais da legalidade, impessoalidade, moralidade, 
publicidade, eficiência e transparência previstos no artigo 37 da Constituição Federal.

A utilização do sistema implica ciência, concordância e aceitação integral das disposições contidas neste Termo, bem como das normas legais aplicáveis, especialmente:
    • Lei Federal nº 12.527/2011 — Lei de Acesso à Informação (LAI);
    • Lei Federal nº 13.709/2018 — Lei Geral de Proteção de Dados Pessoais (LGPD);
    • Constituição Federal;
    • Legislações municipais correlatas;
    • Regimentos internos dos Conselhos Municipais;
    • Normas administrativas expedidas pela Prefeitura Municipal de Pirassununga.


1. FINALIDADE E OBJETIVOS DA PLATAFORMA

O Portal dos Conselhos Municipais possui como objetivos institucionais:
    • Promover a transparência ativa das ações dos Conselhos Municipais;
    • Assegurar o amplo acesso da população às informações públicas;
    • Centralizar documentos oficiais e registros administrativos;
    • Fortalecer os mecanismos de controle social;
    • Ampliar a participação cidadã nas políticas públicas;
    • Padronizar a gestão documental dos conselhos;
    • Garantir maior eficiência administrativa e segurança da informação;
    • Preservar historicamente os atos e deliberações dos Conselhos Municipais.

A plataforma constitui ambiente oficial de publicação institucional, possuindo relevância administrativa, documental e histórica.

2. RESPONSABILIDADES DOS USUÁRIOS
(Gestores, Conselheiros e Responsáveis pelos Conselhos)

Os usuários autorizados a acessar o painel administrativo do sistema assumem integral responsabilidade pelas informações inseridas, modificadas, excluídas, publicadas ou mantidas sob sua autenticação.

Consideram-se usuários autorizados:
    • Representantes dos Conselhos Municipais;
    • Servidores públicos designados;
    • Gestores administrativos;
    • Secretarias vinculadas;
    • Operadores formalmente autorizados pela Administração Pública.

O acesso ao sistema possui caráter pessoal, individual, restrito e intransferível.


2.1 Veracidade, Integridade e Confiabilidade das Informações

O usuário compromete-se a garantir que todas as informações cadastradas no sistema sejam:
    • Verdadeiras;
    • Completas;
    • Atualizadas;
    • Legítimas;
    • Verificáveis;
    • Compatíveis com os documentos oficiais do respectivo conselho.

Incluem-se nesta obrigação:
    • Nomes de membros;
    • Cargos;
    • Mandatos;
    • Contatos institucionais;
    • Endereços;
    • Calendários;
    • Atos normativos;
    • Documentos administrativos;
    • Informações institucionais em geral.

A inserção de informações falsas, incompletas, manipuladas ou desatualizadas poderá configurar infração administrativa, civil e penal.


2.2 Transparência Ativa e Atualização Permanente

Os usuários responsáveis deverão manter permanentemente atualizadas as informações relacionadas aos Conselhos Municipais, garantindo que a população tenha acesso contínuo, claro e tempestivo aos dados públicos.

Deverão ser atualizados imediatamente após publicação oficial:
    • Nomeações;
    • Substituições;
    • Alterações regimentais;
    • Mudanças de endereço;
    • Contatos institucionais;
    • Composição dos conselhos;
    • Calendário de reuniões;
    • Atos deliberativos.

A omissão injustificada de informações obrigatórias poderá caracterizar descumprimento dos deveres de transparência pública.


2.3 Publicação e Gestão de Documentos Oficiais

Os documentos inseridos na plataforma deverão:
    • Corresponder fielmente aos documentos oficiais originais;
    • Estar completos e legíveis;
    • Possuir qualidade adequada de digitalização;
    • Respeitar a integridade documental;
    • Ser publicados exclusivamente em formato PDF, salvo disposição técnica diversa definida pela Administração.

Poderão ser publicados, entre outros:
    • Leis, Decretos, Portarias, Editais,
    • Resoluções;
    • Recomendações/Ofícios;
    • Pautas de reuniões;
    • Atas de reuniões.

O usuário declara que possui autorização e competência funcional para realizar a publicação dos documentos sob sua responsabilidade.


2.4 Cumprimento de Prazos Legais e Regimentais

Os responsáveis pelos Conselhos Municipais comprometem-se a realizar as publicações dentro dos prazos previstos:
    • Na legislação municipal;
    • Nos regimentos internos;
    • Em resoluções específicas;
    • Em determinações administrativas;
    • Em normas de transparência pública.

A observância dos prazos visa assegurar:
    • Publicidade dos atos administrativos;
    • Participação social;
    • Controle público das atividades dos conselhos;
    • Acesso tempestivo à informação.


2.5 Responsabilidade sobre Credenciais de Acesso

As credenciais de acesso ao sistema são pessoais e intransferíveis.

O usuário compromete-se a:
    • Manter sigilo absoluto de login e senha;
    • Não compartilhar acesso com terceiros;
    • Utilizar senhas seguras;
    • Encerrar sessões após utilização;
    • Comunicar imediatamente qualquer suspeita de acesso indevido ou comprometimento da conta.

Toda atividade realizada mediante autenticação válida será presumida como efetuada pelo titular da conta.

A negligência na guarda das credenciais poderá ensejar responsabilização administrativa e funcional.


2.6 Proteção de Dados Pessoais — LGPD

Ao inserir documentos ou informações contendo dados pessoais, o usuário deverá observar rigorosamente os princípios e disposições da Lei Geral de Proteção de Dados Pessoais (LGPD).

O usuário compromete-se a:
    • Divulgar apenas dados estritamente necessários à finalidade pública;
    • Evitar exposição excessiva de dados pessoais;
    • Proteger informações sensíveis;
    • Respeitar os princípios da necessidade, finalidade, adequação e segurança;
    • Verificar previamente a legalidade da divulgação das informações.

Consideram-se dados sensíveis, entre outros:
    • Informações médicas;
    • Dados biométricos;
    • Dados de menores;
    • Informações financeiras;
    • Informações protegidas por sigilo legal.

A publicação indevida de dados pessoais poderá gerar responsabilização individual do agente responsável.


3. RESPONSABILIDADES DA ADMINISTRAÇÃO PÚBLICA
Prefeitura Municipal de Pirassununga

A Prefeitura Municipal de Pirassununga, por meio da Seção de Processamento de Dados (SPD), vinculada à Secretaria Municipal de Administração, na qualidade de administradora tecnológica da plataforma, compromete-se a adotar medidas administrativas e técnicas destinadas à manutenção, segurança, estabilidade e evolução do sistema.


3.1 Disponibilidade e Continuidade do Serviço

A Administração Pública empenhará esforços técnicos razoáveis para manter a plataforma disponível continuamente, em regime permanente de funcionamento.

Entretanto, poderão ocorrer interrupções temporárias decorrentes de:
    • Manutenção preventiva;
    • Atualizações de segurança;
    • Correções emergenciais;
    • Falhas de infraestrutura;
    • Indisponibilidade de serviços externos;
    • Eventos de força maior;
    • Ataques cibernéticos;
    • Falhas de comunicação ou energia.

A Administração não garante disponibilidade absoluta e ininterrupta do sistema.


3.2 Suporte Técnico e Atendimento aos Usuários

A SPD disponibilizará suporte técnico aos usuários autorizados para atendimento relacionado a:
    • Dificuldades de acesso;
    • Recuperação de credenciais;
    • Falhas operacionais;
    • Inconsistências técnicas;
    • Dúvidas de utilização;
    • Problemas relacionados à navegação e publicação.

O suporte não abrange atividades de responsabilidade exclusiva dos conselhos, como elaboração de documentos ou validação de conteúdo administrativo.


3.3 Segurança da Informação e Proteção da Plataforma

A Administração compromete-se a adotar boas práticas de segurança digital e proteção da informação, incluindo:
    • Autenticação de usuários;
    • Controle de permissões;
    • Criptografia quando aplicável;
    • Monitoramento de acessos;
    • Registro de logs;
    • Proteção contra acessos não autorizados;
    • Atualização periódica de sistemas;
    • Mecanismos de prevenção contra falhas e ataques cibernéticos.

Embora sejam adotadas medidas de proteção, nenhum sistema informatizado é absolutamente imune a incidentes de segurança.


3.4 Gestão e Governança de Acessos

A Administração realizará o controle dos níveis de acesso conforme:
    • Solicitações formais das secretarias;
    • Atos administrativos oficiais;
    • Designações funcionais;
    • Critérios de necessidade operacional.

Os acessos poderão ser:
    • Concedidos;
    • Alterados;
    • Suspensos;
    • Revogados;

Sempre que houver necessidade administrativa, desligamento funcional, alteração de competência ou indícios de uso inadequado.


3.5 Evolução Tecnológica e Melhoria Contínua

A Prefeitura Municipal poderá realizar:
    • Atualizações técnicas;
    • Modernizações da interface;
    • Inclusão de funcionalidades;
    • Melhorias de desempenho;
    • Adequações legais;
    • Integrações tecnológicas.

As alterações poderão ocorrer sem a obrigação de aviso prévio individual aos usuários, desde que preservada a finalidade pública da plataforma.


4. AUDITORIA, MONITORAMENTO E REGISTRO DE ATIVIDADES

Por motivos de segurança, transparência, rastreabilidade e controle administrativo, o sistema poderá registrar automaticamente:
    • Data e horário de acesso;
    • Endereço IP;
    • Usuário autenticado;
    • Ações realizadas;
    • Publicações efetuadas;
    • Alterações e exclusões de informações;
    • Movimentações administrativas.

Os registros de auditoria poderão ser utilizados para:
    • Investigação de incidentes;
    • Apuração administrativa;
    • Controle interno;
    • Segurança institucional;
    • Cumprimento de obrigações legais.


5. USO INDEVIDO DA PLATAFORMA

Constituem uso indevido da plataforma, entre outros:
    • Utilização para fins particulares ou não institucionais;
    • Inserção deliberada de informações falsas;
    • Adulteração documental;
    • Exclusão indevida de informações públicas;
    • Compartilhamento de credenciais;
    • Tentativa de acesso não autorizado;
    • Violação de segurança;
    • Divulgação indevida de dados pessoais;
    • Descumprimento das obrigações de transparência pública.

O uso indevido poderá acarretar:
    • Bloqueio ou suspensão imediata do acesso;
    • Revogação de permissões;
    • Abertura de procedimento administrativo;
    • Responsabilização civil;
    • Responsabilização penal;
    • Aplicação de sanções previstas na legislação vigente.


6. DISPOSIÇÕES FINAIS

O presente Termo possui validade por prazo indeterminado e aplica-se a todos os usuários que acessarem o sistema, independentemente do nível de permissão concedido.

A Administração Pública poderá revisar, atualizar ou modificar este Termo a qualquer momento, visando adequações:
    • Legais;
    • Técnicas;
    • Administrativas;
    • Operacionais;
    • Institucionais.

As versões atualizadas passarão a produzir efeitos imediatamente após sua publicação na plataforma.

Ao realizar o primeiro acesso ao Portal dos Conselhos Municipais de Pirassununga, o usuário declara expressamente que:
    • Leu integralmente este Termo;
    • Compreendeu todas as disposições aqui previstas;
    • Concorda integralmente com suas condições;
    • Assume plena responsabilidade pelas ações realizadas mediante sua autenticação no sistema.
