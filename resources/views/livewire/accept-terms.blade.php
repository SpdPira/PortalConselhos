                <pre style='font-family: "Instrument Sans", sans-serif;'>

<strong>TERMO DE CIÊNCIA, RESPONSABILIDADE, USO E GOVERNANÇA DA INFORMAÇÃO</strong>
<i>Portal dos Conselhos Municipais de Pirassununga </i>
</pre>
O   presente   Termo   de   Consentimento,   Responsabilidade,   Uso   e   Governança   da   Informação 
estabelece   as   regras,   diretrizes,   obrigações,   responsabilidades   e   condições   de   utilização   da 
plataforma eletrônica denominada Portal dos Conselhos Municipais de Pirassununga, mantida pela 
Prefeitura Municipal de Pirassununga. <br><br>

A plataforma possui caráter público, institucional e permanente, sendo destinada à centralização, 
organização,   gerenciamento,   armazenamento   e   divulgação   de   informações   relacionadas   aos 
Conselhos  Municipais  de Políticas  Públicas, seus  membros, atos  administrativos, deliberações, 
documentos oficiais e demais registros de interesse coletivo. <br><br>

O Portal constitui instrumento oficial de transparência pública, participação social, controle cidadão 
e     publicidade     administrativa,     observando     os     princípios     constitucionais     da     legalidade, 
impessoalidade,   moralidade,   publicidade,   eficiência   e   transparência   previstos   no   artigo   37   da 
Constituição Federal. <br><br>

A utilização do sistema implica ciência, concordância e aceitação integral das disposições contidas 
neste Termo, bem como das normas legais aplicáveis, especialmente: <br><pre style='font-family: "Instrument Sans", sans-serif;'>
    •   Lei Federal nº 12.527/2011 — Lei de Acesso à Informação (LAI); 
    •   Lei Federal nº 13.709/2018 — Lei Geral de Proteção de Dados Pessoais (LGPD); 
    •   Lei Municipal nº 6.590/2026 – Portal dos Conselhos Municipais; 
    •   Constituição Federal; 
    •   Legislações municipais correlatas; 
    •   Regimentos internos dos Conselhos Municipais; 
    •   Normas administrativas expedidas pela Prefeitura Municipal de Pirassununga. 

<strong>1. FINALIDADE E OBJETIVOS DA PLATAFORMA </strong>

O Portal dos Conselhos Municipais possui como objetivos institucionais: 
    •   Promover a transparência ativa das ações dos Conselhos Municipais; 
    •   Assegurar o amplo acesso da população às informações públicas; 
    •   Centralizar documentos oficiais e registros administrativos; 
    •   Fortalecer os mecanismos de controle social; 
    •   Padronizar a gestão documental dos conselhos; 
    •   Garantir maior eficiência administrativa e segurança da informação; 
    •   Preservar historicamente os atos e deliberações dos Conselhos Municipais. </pre>

A   plataforma   constitui   ambiente   oficial   de   publicação   institucional,   possuindo   relevância 
administrativa, documental e histórica. <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
<strong>2. RESPONSABILIDADES DOS USUÁRIOS </strong>
(Gestores, Conselheiros e Responsáveis pelos Conselhos) </pre>

Os   usuários   autorizados   a   acessar   o   painel   administrativo   do   sistema   assumem   integral 
responsabilidade pelas informações inseridas, modificadas, excluídas, publicadas ou mantidas sob 
sua autenticação. <br><br>

O acesso ao sistema possui caráter pessoal, individual, restrito e intransferível. <br><br>

A Prefeitura disponibilizará acesso a 1 (um) usuário por Conselho, podendo ampliar ou restringir tal 
quantidade conforme critérios administrativos e operacionais. <br><br>

O referido usuário será indicado pelo Conselho através de ofício à Seção de Processamento de 
Dados desta Prefeitura. <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
<strong>2.1 Veracidade, Integridade e Confiabilidade das Informações </strong>

O usuário compromete-se a garantir que todas as informações cadastradas no sistema sejam: 
    •   Verdadeiras; 
    •   Completas; 
    •   Atualizadas; 
    •   Legítimas; 
    •   Verificáveis; 
    •   Compatíveis com os documentos oficiais do respectivo conselho. 

Incluem-se nesta obrigação: 
    •   Nomes de membros; 
    •   Cargos; 
    •   Mandatos; 
    •   Contatos institucionais; 
    •   Endereços; 
    •   Calendários; 
    •   Atos normativos; 
    •   Documentos administrativos; 
    •   Informações institucionais em geral. 

O usuário, quando da publicação, deve atentar-se a não publicar dados pessoais desnecessários, tais como: 
    •   CPF e RG; 
    •   endereço residencial; 
    •   telefone particular; 
    •   assinatura manuscrita; 
    •   dados bancários; 
    •   informações de saúde; 
    •   dados individualizados de crianças e adolescentes; 
    •   informações protegidas por sigilo.  </pre>

A inserção de informações falsas, incompletas, manipuladas ou desatualizadas poderá configurar 
infração administrativa, civil e penal. <br><br>

<strong>2.2 Transparência Ativa e Atualização Permanente </strong><br><br>

Os usuários responsáveis deverão manter permanentemente atualizadas as informações relacionadas 
aos Conselhos Municipais, garantindo que a população tenha acesso contínuo, claro e tempestivo 
aos dados públicos. <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
Deverão ser atualizados imediatamente após publicação oficial: 
    •   Nomeações; 
    •   Substituições; 
    •   Alterações regimentais; 
    •   Mudanças de endereço; 
    •   Contatos institucionais; 
    •   Composição dos conselhos; 
    •   Calendário de reuniões; 
    •   Atos deliberativos. </pre>

A  omissão   injustificada   de   informações   obrigatórias   poderá   caracterizar   descumprimento   dos 
deveres de transparência pública. <br><br>

<pre style='font-family: "Instrument Sans", sans-serif;'>
<strong>2.3 Publicação e Gestão de Documentos Oficiais</strong>

Os documentos inseridos na plataforma deverão: 
    •   Corresponder fielmente aos documentos oficiais originais; 
    •   Estar completos e legíveis; 
    •   Possuir qualidade adequada de digitalização; 
    •   Respeitar a integridade documental; 
    •   Ser publicados exclusivamente em formato PDF, salvo disposição técnica diversa definida pela Administração. 

Poderão ser publicados, entre outros: 
    •   Leis, Decretos, Portarias, Editais, 
    •   Resoluções; 
    •   Recomendações/Ofícios; 
    •   Pautas de reuniões; 
    •   Atas de reuniões. </pre>

O usuário declara que possui autorização e competência funcional para realizar a publicação dos 
documentos sob sua responsabilidade. <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
<strong>2.4 Cumprimento de Prazos Legais e Regimentais </strong>

Os responsáveis pelos Conselhos Municipais comprometem-se a realizar as publicações dentro dos prazos previstos: 
    •   Na legislação municipal; 
    •   Nos regimentos internos; 
    •   Em resoluções específicas; 
    •   Em determinações administrativas; 
    •   Em normas de transparência pública. 

A observância dos prazos visa assegurar: 
    •   Publicidade dos atos administrativos; 
    •   Participação social; 
    •   Controle público das atividades dos conselhos; 
    •   Acesso tempestivo à informação. 

<strong>2.5 Responsabilidade sobre Credenciais de Acesso </strong>

As credenciais de acesso ao sistema são pessoais e intransferíveis. 

O usuário compromete-se a: 
    •   Manter sigilo absoluto de login e senha; 
    •   Não compartilhar acesso com terceiros; 
    •   Utilizar senhas seguras; 
    •   Encerrar sessões após utilização; 
    •   Comunicar imediatamente qualquer suspeita de acesso indevido ou comprometimento da conta. 

Toda atividade realizada mediante autenticação válida será presumida como efetuada pelo titular da conta. 

A negligência na guarda das credenciais poderá ensejar responsabilização administrativa e funcional. 

<strong>2.6 Proteção de Dados Pessoais — LGPD </strong></pre>

Ao inserir documentos ou informações contendo dados pessoais, o usuário deverá observar 
rigorosamente os princípios e disposições da Lei Geral de Proteção de Dados Pessoais (LGPD). <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
O usuário compromete-se a: 
    •   Divulgar apenas dados estritamente necessários à finalidade pública; 
    •   Evitar exposição excessiva de dados pessoais; 
    •   Proteger informações sensíveis; 
    •   Respeitar os princípios da necessidade, finalidade, adequação e segurança; 
    •   Verificar previamente a legalidade da divulgação das informações. 

Consideram-se dados sensíveis, entre outros: 
    •   Informações médicas; 
    •   Dados biométricos; 
    •   Dados de menores; 
    •   Informações financeiras; 
    •   Informações protegidas por sigilo legal. 

A publicação indevida de dados pessoais poderá gerar responsabilização individual do agente responsável. 

<strong>3. RESPONSABILIDADES DA ADMINISTRAÇÃO PÚBLICA </strong>
Prefeitura Municipal de Pirassununga </pre>

A Prefeitura Municipal de Pirassununga, por meio da Seção de Processamento de Dados (SPD), 
vinculada à Secretaria Municipal de Administração, na qualidade de administradora tecnológica da 
plataforma, compromete-se a adotar medidas administrativas e técnicas destinadas à manutenção, 
segurança e estabilidade do sistema. <br><br>

<strong>3.1 Disponibilidade e Continuidade do Serviço </strong><br><br>

A   Administração   Pública   empenhará   esforços   técnicos   razoáveis   para   manter   a   plataforma 
disponível continuamente, em regime permanente de funcionamento. <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
Entretanto, poderão ocorrer interrupções temporárias decorrentes de: 
    •   Manutenção preventiva; 
    •   Atualizações de segurança; 
    •   Correções emergenciais; 
    •   Falhas de infraestrutura; 
    •   Indisponibilidade de serviços externos; 
    •   Eventos de força maior; 
    •   Ataques cibernéticos; 
    •   Falhas de comunicação ou energia. 

A Administração não garante disponibilidade absoluta e ininterrupta do sistema. 

<strong>3.2 Suporte Técnico e Atendimento aos Usuários </strong>

A SPD disponibilizará suporte técnico aos usuários autorizados para atendimento relacionado a: 
    •   Dificuldades de acesso; 
    •   Recuperação de credenciais; 
    •   Falhas operacionais; 
    •   Inconsistências técnicas; 
    •   Dúvidas de utilização; 
    •   Problemas relacionados à navegação e publicação. </pre>

O suporte não abrange atividades de responsabilidade exclusiva dos conselhos, como elaboração de 
documentos ou validação de conteúdo administrativo. <br><br>

<strong>3.3 Segurança da Informação e Proteção da Plataforma </strong><br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
A Administração compromete-se a adotar boas práticas de segurança digital e proteção da informação, incluindo: 
    •   Autenticação de usuários; 
    •   Controle de permissões; 
    •   Criptografia quando aplicável; 
    •   Monitoramento de acessos; 
    •   Registro de logs; 
    •   Proteção contra acessos não autorizados; 
    •   Atualização periódica de sistemas; 
    •   Mecanismos de prevenção contra falhas e ataques cibernéticos. </pre>

Embora sejam adotadas medidas de proteção, nenhum sistema informatizado é absolutamente 
imune a incidentes de segurança. <br><br>

<strong>3.4 Gestão e Governança de Acessos </strong><br><br>

A Administração realizará o controle dos níveis de acesso conforme solicitações formais dos 
Conselhos mediante avaliação de Atos administrativos oficiais. <br><br>

Os acessos poderão ser Concedidos ou Revogados sempre que houver necessidade administrativa, 
desligamento funcional, alteração de competência ou indícios de uso inadequado. <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
<strong>3.5 Evolução Tecnológica e Melhoria Contínua </strong>

A Prefeitura Municipal poderá realizar: 
    •   Atualizações técnicas de segurança; 
    •   Melhorias de desempenho; 
    •   Adequações legais; </pre>

As alterações poderão ocorrer sem a obrigação de aviso prévio individual aos usuários, desde que 
preservada a finalidade pública da plataforma. <br><br>

<strong>3.6 Responsabilidade pelo Conteúdo Publicado </strong><br><br>

A   Prefeitura   Municipal   de   Pirassununga   disponibiliza   o   Portal   dos   Conselhos   Municipais 
exclusivamente como plataforma tecnológica destinada à publicação e divulgação das informações 
fornecidas pelos respectivos Conselhos Municipais. <br><br>

A responsabilidade pela elaboração, veracidade, autenticidade, legalidade, atualização, integridade e 
manutenção   das   informações,   documentos,   atas,   resoluções,   pautas,   comunicados   e   demais 
conteúdos publicados é exclusiva do respectivo Conselho Municipal e do usuário formalmente 
indicado para sua gestão. <br><br>

A Prefeitura Municipal de Pirassununga, por intermédio da Seção de Processamento de Dados, não 
realiza análise prévia, validação jurídica, revisão de mérito, conferência documental ou auditoria 
permanente dos conteúdos publicados pelos Conselhos. <br><br>

Eventuais erros, omissões, inconsistências, informações desatualizadas, divulgações indevidas de 
dados pessoais, descumprimento de obrigações legais ou regimentais e quaisquer danos decorrentes 
do conteúdo publicado serão de responsabilidade exclusiva do Conselho Municipal responsável 
pela publicação e de seus agentes competentes. <br><br>

A   Prefeitura   Municipal   de   Pirassununga   não   poderá   ser   responsabilizada   por   decisões, 
manifestações, deliberações, opiniões, documentos  ou informações  divulgadas pelos  Conselhos 
Municipais por meio da plataforma. <br><br>

<strong>3.7 Solicitações de Alteração, Correção ou Exclusão de Conteúdo </strong><br><br>

Pedidos   de   inclusão,   alteração,   correção,   atualização   ou   exclusão   de   informações   publicadas 
deverão ser encaminhados diretamente ao Conselho Municipal responsável pelo conteúdo. <br><br>

A Prefeitura Municipal de Pirassununga não possui competência para alterar, complementar ou 
remover conteúdos publicados sem solicitação formal do respectivo Conselho ou determinação 
legal, judicial ou administrativa competente. <br><br>

A atuação da Seção de Processamento de Dados limita-se à administração técnica da plataforma, 
não abrangendo a gestão do conteúdo institucional dos Conselhos Municipais. <br><br>

<strong>3.8 Limitação de Obrigações da Administração da Plataforma </strong><br><br>

A  disponibilização   do   Portal   dos   Conselhos   Municipais   não   implica   obrigação   da   Prefeitura 
Municipal de Pirassununga de promover customizações específicas, desenvolvimento de novas 
funcionalidades,   alterações   de   layout,   integrações   com   sistemas   externos   ou   atendimento   de 
demandas particulares dos Conselhos Municipais. <br><br>

As evoluções tecnológicas da plataforma serão definidas pela Administração Municipal de acordo 
com critérios de interesse público, disponibilidade técnica, viabilidade operacional e conveniência 
administrativa. <br><br>

Solicitações  de melhorias  poderão  ser apresentadas  pelos  Conselhos  Municipais, sem que sua 
implementação constitua obrigação da Administração. <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
<strong>4. USO INDEVIDO DA PLATAFORMA </strong>

Constituem uso indevido da plataforma, entre outros: 
    •   Utilização para fins particulares ou não institucionais; 
    •   Utilização para fins de promoção política ou partidária; 
    •   Inserção deliberada de informações falsas; 
    •   Adulteração documental; 
    •   Exclusão indevida de informações públicas; 
    •   Compartilhamento de credenciais; 
    •   Tentativa de acesso não autorizado; 
    •   Violação de segurança; 
    •   Divulgação indevida de dados pessoais; 
    •   Descumprimento das obrigações de transparência pública. 

O uso indevido poderá acarretar: 
    •   Bloqueio ou suspensão imediata do acesso; 
    •   Revogação de permissões; 
    •   Abertura de procedimento administrativo; 
    •   Responsabilização civil; 
    •   Responsabilização penal; 
    •   Aplicação de sanções previstas na legislação vigente. 

<strong>6. DISPOSIÇÕES FINAIS </strong></pre>

O presente Termo possui validade por prazo indeterminado e aplica-se a todos os usuários que 
acessarem o sistema, independentemente do nível de permissão concedido. <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
A Administração Pública poderá revisar, atualizar ou modificar este Termo a qualquer momento, visando adequações: 
    •   Legais; 
    •   Técnicas; 
    •   Administrativas; 
    •   Operacionais; 
    •   Institucionais. </pre>

As   versões   atualizadas   passarão   a   produzir   efeitos   imediatamente   após   sua   publicação   na 
plataforma. <br><br>
<pre style='font-family: "Instrument Sans", sans-serif;'>
Ao realizar o primeiro acesso ao Portal dos Conselhos Municipais de Pirassununga, o usuário declara expressamente que: 
    •   Leu integralmente este Termo; 
    •   Compreendeu todas as disposições aqui previstas; 
    •   Concorda integralmente com suas condições; 
    •   Assume plena responsabilidade pelas ações realizadas mediante sua autenticação no sistema. 

</pre><br>
